use serde::Deserialize;

#[derive(Debug, Deserialize, Clone)]
pub struct ProgramPathPayload {
    /// The program's ID or its slug.
    pub program: String,
}

#[derive(Debug, Deserialize, Clone)]
pub struct CreateFolderBodyPayload {
    pub name: String,
    pub parent_id: Option<String>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct FolderPathPayload {
    pub program: String,
    pub folder: String,
}

#[derive(Debug, Deserialize, Clone)]
pub struct UpdateFolderBodyPayload {
    pub name: Option<String>,
}

#[derive(Debug, Deserialize, Clone, Default)]
pub struct ListDocumentsQueryPayload {
    pub folder_id: Option<String>,
    /// `recent`, `needs_review` or `quarantined`. Omit for All files.
    pub location: Option<String>,
    /// A prefix of the file name (case-insensitive).
    pub q: Option<String>,
    pub max_page_size: Option<i64>,
    pub page_token: Option<String>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct CreateDocumentBodyPayload {
    /// The file name shown in the list. Only a label: the storage key is generated by the server.
    pub name: String,
    /// Defaults to the General folder.
    pub folder_id: Option<String>,
    pub content_type: String,
    pub size_bytes: i64,
    /// SHA-256 of the file in hex; when given, the storage itself refuses an upload that differs.
    pub checksum: Option<String>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct DocumentPathPayload {
    pub program: String,
    pub document: String,
}

#[derive(Debug, Deserialize, Clone)]
pub struct UpdateDocumentBodyPayload {
    pub name: Option<String>,
    pub folder_id: Option<String>,
}

#[derive(Debug, Deserialize, Clone)]
pub struct ReviewDocumentBodyPayload {
    /// `approve` or `reject`.
    pub decision: String,
    pub note: Option<String>,
}

/// What the scanner posts.
#[derive(Debug, Deserialize, Clone)]
pub struct DocumentScanBodyPayload {
    pub document_id: String,
    /// `clean`, `suspicious` or `infected`.
    pub result: String,
    pub scanner: Option<String>,
}
