-- Modules a program has chosen. THE hottest read in the admin API (every screen
-- open): `WHERE program_id = $1` is a prefix scan of the primary key, so no other
-- index is needed. Updates touch `enabled` / `position` / `version`, never the
-- key, so fillfactor 80 keeps them HOT.
CREATE TABLE IF NOT EXISTS program_modules (
    program_id UUID NOT NULL REFERENCES programs (id) ON DELETE CASCADE,
    module_id UUID NOT NULL REFERENCES module_definitions (id) ON DELETE RESTRICT,
    enabled BOOLEAN NOT NULL DEFAULT true,
    -- What the admin made this leaf: `rule` (the leaf IS a rule-engine rule set) or
    -- `settings` (the admin adds settings to it). NULL until chosen, and always NULL on
    -- modules that are not configurable. The leaf's NAME is fixed by the module
    -- ("Pre Enrollment"), so there is no separate component to name. Premade modules may
    -- only use `settings`. The mode cannot change once the leaf has settings or a rule set.
    mode TEXT,
    -- Display order inside this program (the registry's `position` is the default).
    position INT NOT NULL DEFAULT 0,
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    version INT NOT NULL DEFAULT 1,
    create_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (program_id, module_id)
) WITH (fillfactor = 80);

-- Overview counters: ONE ROW PER PROGRAM, updated in the same transaction as each
-- change, so the Overview page is a single primary-key read, never a COUNT(*).
CREATE TABLE IF NOT EXISTS program_stats (
    program_id UUID PRIMARY KEY REFERENCES programs (id) ON DELETE CASCADE,
    total_applications INT NOT NULL DEFAULT 0,
    pending_approvals INT NOT NULL DEFAULT 0,
    active_enrollments INT NOT NULL DEFAULT 0,
    enrollments_total INT NOT NULL DEFAULT 0,
    update_time TIMESTAMPTZ NOT NULL DEFAULT now()
) WITH (fillfactor = 70);

-- ── Settings: what the admin adds to a leaf whose mode is `settings` ──────────────
-- "Add Setting name" + a type from the dropdown. The composite foreign key means a
-- setting can only live in a module this program actually chose. `key` is generated by
-- the server from `name`, so nobody types an identifier. A setting's type never changes
-- once values exist.
CREATE TABLE IF NOT EXISTS program_fields (
    id UUID PRIMARY KEY,
    program_id UUID NOT NULL,
    module_id UUID NOT NULL,
    name TEXT NOT NULL,
    key TEXT NOT NULL,
    -- boolean | number | text | radio | checkbox | dropdown
    field_type TEXT NOT NULL,
    -- For radio / checkbox / dropdown: `manual` (the admin's own values, in field_options) OR
    -- `library` (the library is the ONLY source; nothing is copied here). Never mixed.
    -- NULL for boolean / number / text.
    options_source TEXT,
    -- Opaque id owned by global-settings, so deliberately NOT a foreign key.
    library_id UUID,
    required BOOLEAN NOT NULL DEFAULT false,
    default_value JSONB,
    position INT NOT NULL DEFAULT 0,
    state TEXT NOT NULL DEFAULT 'ACTIVE',
    create_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (program_id, module_id)
        REFERENCES program_modules (program_id, module_id) ON DELETE CASCADE
);

-- A key is unique within a module among live settings.
CREATE UNIQUE INDEX IF NOT EXISTS uq_program_fields_key_active
    ON program_fields (program_id, module_id, key) WHERE state = 'ACTIVE';
-- Page load: a module's settings in display order, one index range.
CREATE INDEX IF NOT EXISTS idx_program_fields_module_position_id
    ON program_fields (program_id, module_id, position, id) WHERE state = 'ACTIVE';
-- Webhook path: "which settings draw from the library that just changed?"
CREATE INDEX IF NOT EXISTS idx_program_fields_library_id
    ON program_fields (library_id) WHERE library_id IS NOT NULL;

-- Values the admin typed in for radio / checkbox / dropdown settings. `code` is the identity
-- of an option: a removed option is deactivated (not deleted) so saved values never break.
-- Library options are NOT copied here: they are read from global-settings.
CREATE TABLE IF NOT EXISTS field_options (
    id UUID PRIMARY KEY,
    field_id UUID NOT NULL REFERENCES program_fields (id) ON DELETE CASCADE,
    code TEXT NOT NULL,
    label TEXT NOT NULL,
    position INT NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT true,
    create_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (field_id, code)
);
CREATE INDEX IF NOT EXISTS idx_field_options_field_position_id
    ON field_options (field_id, position, id);

-- Saved values: ONE ROW PER SETTING PER SCOPE. A multi-select keeps its picks in
-- `option_ids UUID[]` on that one row (manual and library options are both UUIDs), so a
-- form save is one upsert per changed setting and a form load reads one row per setting.
CREATE TABLE IF NOT EXISTS program_field_values (
    program_id UUID NOT NULL REFERENCES programs (id) ON DELETE CASCADE,
    field_id UUID NOT NULL REFERENCES program_fields (id) ON DELETE CASCADE,
    scope_type TEXT NOT NULL DEFAULT 'program',
    scope_id TEXT NOT NULL DEFAULT '',
    value JSONB,
    option_ids UUID[] NOT NULL DEFAULT '{}',
    -- Copied from the setting at write time so the reverse lookup needs no join.
    library_id UUID,
    create_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (program_id, field_id, scope_type, scope_id)
) WITH (fillfactor = 80);

-- Webhook reverse lookup: "which programs use library X?"
CREATE INDEX IF NOT EXISTS idx_program_field_values_library_program
    ON program_field_values (library_id, program_id) WHERE library_id IS NOT NULL;
-- "Which programs picked option Y?" — flags drift when an option is deactivated.
CREATE INDEX IF NOT EXISTS idx_program_field_values_option_ids
    ON program_field_values USING GIN (option_ids);
